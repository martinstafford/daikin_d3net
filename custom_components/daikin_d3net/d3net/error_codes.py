def lookup_error_message(code: str | None) -> str | None:
    """Return the description for a two-character Daikin error code."""
    if not code:
        return None
    normalized = code.strip().upper()
    if not normalized or normalized in {"00", "0"}:
        return None
    return ERROR_CODE_MAPPING.get(normalized)

